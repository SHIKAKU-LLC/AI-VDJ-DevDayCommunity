const isCode=v=>typeof v==='string'&&(known.has(v)||/^RUNTIME_HTTP_[1-5][0-9]{2}_HOLD$/.test(v));
export function diagnosticReasons(error){
 const reasons=[],seen=new Set();
 for(let e=error;e&&typeof e==='object'&&!seen.has(e)&&seen.size<6;e=e.cause){
  seen.add(e);
  const value=[e.holdReason,e.code,e.message].find(isCode);
  if(value&&!reasons.includes(value))reasons.push(value);
 }
 return reasons.length?reasons:['EXECUTION_HOLD'];
}
